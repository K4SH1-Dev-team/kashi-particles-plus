# Copies the pure-Java core (parser + MoLang evaluator) and the mod-side runtime into every test
# workspace's source tree.
#
# The core is the one source of truth under core/src/main/java. During mod-side development we
# compile it as part of the workspace so the runtime can call it; once the plugin ships it via
# templates, this copy is what those templates will mirror. Re-run after editing anything in core,
# runtime, or a generator's overlay directory (see make-runtime-templates.ps1).
#
# One workspace per generator this plugin supports, same list as make-runtime-templates.ps1 - each
# workspace gets runtime/ verbatim except for files its generator's overlay replaces, so what gets
# compiled here matches what that generator would actually ship.

$ErrorActionPreference = "Stop"

$project = Split-Path -Parent $PSScriptRoot
# The repo (this script's parent tree) and the local-only dev environment (test workspaces) are
# sibling folders under the project root - see docs/DEVELOPMENT.md.
$localRoot = Join-Path (Split-Path -Parent $project) "local"

# One entry per test workspace. "Overlay" mirrors make-runtime-templates.ps1's $generators list -
# a directory laid out like runtime/ whose files replace the shared ones for that workspace only.
# Which MCreator install/JDK a workspace was built with doesn't matter here - this script only
# copies .java source, it never invokes a compiler (see check-mod-compile.ps1 for that).
$workspaces = @(
    [pscustomobject]@{ Name = "kashi_particle_test"; Overlay = $null },
    [pscustomobject]@{ Name = "teste_vinte_oito";    Overlay = "runtime-1.21.8" },
    [pscustomobject]@{ Name = "true_particle_test";  Overlay = $null }
)

foreach ($ws in $workspaces) {
    $wsPath = Join-Path $localRoot "workspace\$($ws.Name)"
    if (-not (Test-Path $wsPath)) {
        Write-Host "[$($ws.Name)] workspace not found at $wsPath - skipped"
        continue
    }

    $wsRoot = Join-Path $wsPath "src\main\java\net\kashi\particles"

    # core (parser + MoLang) and runtime (particle engine) both live in the project; the workspace
    # gets a copy purely so the fast javac check and in-game testing have something to compile.
    $packages = @(
        @{ From = Join-Path $project "core\src\main\java\net\kashi\particles\core";       To = Join-Path $wsRoot "core" },
        @{ From = Join-Path $project "runtime\src\main\java\net\kashi\particles\runtime"; To = Join-Path $wsRoot "runtime" }
    )

    foreach ($package in $packages) {
        if (-not (Test-Path $package.From)) { throw "sources not found at $($package.From)" }

        if (Test-Path $package.To) { Remove-Item $package.To -Recurse -Force }
        New-Item -ItemType Directory -Path $package.To -Force | Out-Null

        Copy-Item (Join-Path $package.From "*") $package.To -Recurse -Force
    }

    # Overlay files replace the shared ones just copied above - same file, this workspace's
    # generator-specific content instead.
    if ($ws.Overlay) {
        $overlayRoot = Join-Path $project "$($ws.Overlay)\src\main\java\net\kashi\particles\runtime"
        if (-not (Test-Path $overlayRoot)) { throw "overlay root not found: $overlayRoot" }

        Get-ChildItem $overlayRoot -Filter "*.java" | ForEach-Object {
            Copy-Item $_.FullName (Join-Path $wsRoot "runtime") -Force
        }
    }

    # Kept out for the same reason make-runtime-templates.ps1 skips it: the diagnostics are an
    # authoring tool compiled into the plugin, never part of a generated mod. The workspace mirrors
    # what ships.
    Remove-Item (Join-Path $wsRoot "core\ParticleDiagnostics.java") -Force -EA SilentlyContinue

    # KashiParticleEffects is generated by the plugin from the workspace's elements. MCreator
    # writes the real one to this exact path on the next build; this placeholder only keeps the
    # standalone javac check compiling in the meantime.
    $placeholder = Join-Path $wsRoot "runtime\KashiParticleEffects.java"

    $stub = @'
package net.kashi.particles.runtime;

/** Dev placeholder - MCreator generates the real one from the workspace's KASHI Particle elements. */
public final class KashiParticleEffects {

	private KashiParticleEffects() {
	}

	public static void registerAll() {
	}
}
'@

    # WriteAllText, not Set-Content: PowerShell 5.1 writes UTF-8 WITH a BOM, and javac rejects a
    # BOM with "illegal character: '﻿'".
    [System.IO.File]::WriteAllText($placeholder, $stub)

    $count = (Get-ChildItem $wsRoot -Recurse -Filter "*.java").Count
    Write-Host "[$($ws.Name)] synced core + runtime -> $count java files (incl. KashiParticleEffects placeholder)"
}
